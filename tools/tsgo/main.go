// Command tsgo writes Go types for every exported type in ../ai-coding-tool/src/{domain,contracts,application,host}:
// extract.mjs reads them with the TypeScript compiler, and this program writes internal/<layer>/<file>_types.go.
//
//	go run ./tools/tsgo [-src ../ai-coding-tool/src] [-ir tree.json] [-dump tree.json]
package main

import (
	"bytes"
	"encoding/json/v2"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"
)

const header = "// Code generated by tools/tsgo"

func main() {
	root := repoRoot()
	src := flag.String("src", filepath.Join(root, "..", "ai-coding-tool", "src"), "the TypeScript app's src directory")
	irFile := flag.String("ir", "", "read the extracted tree from this file instead of running extract.mjs")
	dump := flag.String("dump", "", "also write the extracted tree here")
	flag.Parse()

	data, err := extracted(root, *src, *irFile)
	if err != nil {
		fail(err)
	}
	if *dump != "" {
		if err := os.WriteFile(*dump, data, 0o644); err != nil {
			fail(err)
		}
	}
	var tree ir
	if err := json.Unmarshal(data, &tree); err != nil {
		fail(err)
	}
	for _, p := range tree.Problems {
		if !ignoredProblem(p) {
			fmt.Fprintln(os.Stderr, "extract:", p)
		}
	}
	g := newGen(&tree)
	for _, d := range tree.Decls {
		g.emitDecl(d)
	}
	written, err := g.write(filepath.Join(root, "internal"))
	if err != nil {
		fail(err)
	}
	for _, p := range g.problems {
		fmt.Fprintln(os.Stderr, "tsgo:", p)
	}
	fmt.Printf("tsgo: %d declarations, %d files\n", len(tree.Decls), written)
	if len(g.problems) > 0 {
		os.Exit(1)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "tsgo:", err)
	os.Exit(1)
}

func repoRoot() string {
	dir, err := os.Getwd()
	if err != nil {
		fail(err)
	}
	for d := dir; ; d = filepath.Dir(d) {
		if _, err := os.Stat(filepath.Join(d, "go.mod")); err == nil {
			return d
		}
		if filepath.Dir(d) == d {
			fail(fmt.Errorf("no go.mod above %s", dir))
		}
	}
}

func extracted(root, src, irFile string) ([]byte, error) {
	if irFile != "" {
		return os.ReadFile(irFile)
	}
	tool := filepath.Join(root, "tools", "tsgo")
	if _, err := os.Stat(filepath.Join(tool, "node_modules", "typescript")); err != nil {
		install := exec.Command("npm", "ci", "--no-audit", "--no-fund")
		install.Dir, install.Stdout, install.Stderr = tool, os.Stderr, os.Stderr
		if err := install.Run(); err != nil {
			return nil, fmt.Errorf("npm ci in tools/tsgo: %w", err)
		}
	}
	cmd := exec.Command("node", filepath.Join(tool, "extract.mjs"), src)
	cmd.Stderr = os.Stderr
	return cmd.Output()
}

var (
	litPattern   = regexp.MustCompile("\x00LIT:(.*?)\x00")
	unionPattern = regexp.MustCompile("\x00UNION:(.*?)\x00")
)

func (g *gen) nameLits() map[string]string {
	texts := make([]string, 0, len(g.lits))
	for text := range g.lits {
		texts = append(texts, text)
	}
	sort.Strings(texts)
	used := map[string]bool{}
	names := map[string]string{}
	for _, text := range texts {
		var v any
		if err := json.Unmarshal([]byte(text), &v); err != nil {
			fail(err)
		}
		want := valueName(v)
		if b, ok := v.(bool); ok {
			want = "Bool" + valueName(b)
		}
		name := want
		for i := 2; used[name]; i++ {
			name = fmt.Sprintf("%s%d", want, i)
		}
		used[name] = true
		names[text] = name
	}
	return names
}

func (g *gen) write(internal string) (int, error) {
	lits := g.nameLits()
	keep := map[string]bool{}
	var tsFiles []string
	for ts := range g.files {
		tsFiles = append(tsFiles, ts)
	}
	sort.Strings(tsFiles)
	outs := map[string]string{}
	for _, ts := range tsFiles {
		f := g.files[ts]
		if f.body.Len() == 0 && len(f.methods) == 0 && len(f.registers) == 0 {
			continue
		}
		if prev, ok := outs[f.layer+"/"+f.out]; ok {
			return 0, fmt.Errorf("src/%s and src/%s both map to %s", prev, ts, f.out)
		}
		outs[f.layer+"/"+f.out] = ts
		var out bytes.Buffer
		fmt.Fprintf(&out, "%s from src/%s. DO NOT EDIT.\n\npackage %s\n\n", header, ts, f.layer)
		imports := make([]string, 0, len(f.imports))
		for imp := range f.imports {
			imports = append(imports, imp)
		}
		sort.Strings(imports)
		if len(imports) > 0 {
			out.WriteString("import (\n")
			for _, imp := range imports {
				fmt.Fprintf(&out, "%q\n", imp)
			}
			out.WriteString(")\n\n")
		}
		out.Write(f.body.Bytes())
		methods := make([]string, 0, len(f.methods))
		for m := range f.methods {
			methods = append(methods, m)
		}
		sort.Strings(methods)
		for _, m := range methods {
			out.WriteString(m + "\n")
		}
		if len(f.registers) > 0 {
			out.WriteString("\nfunc init() {\n")
			for _, r := range f.registers {
				out.WriteString(r + "\n")
			}
			out.WriteString("}\n")
		}
		text := litPattern.ReplaceAllStringFunc(out.String(), func(s string) string {
			return lits[litPattern.FindStringSubmatch(s)[1]]
		})
		text = unionPattern.ReplaceAllStringFunc(text, func(s string) string {
			key := unionPattern.FindStringSubmatch(s)[1]
			info := g.unions[key]
			markers := []string{info.marker}
			var supers []string
			for m := range g.supers[key] {
				if m != info.marker {
					supers = append(supers, m)
				}
			}
			sort.Strings(supers)
			markers = append(markers, supers...)
			return fmt.Sprintf("type %s interface {\n%s()\n}", info.ref.name, strings.Join(markers, "()\n"))
		})
		src, err := format.Source([]byte(text))
		if err != nil {
			os.WriteFile(filepath.Join(os.TempDir(), "tsgo-"+f.out), []byte(text), 0o644)
			return 0, fmt.Errorf("%s: %w", f.out, err)
		}
		path := filepath.Join(internal, f.layer, f.out)
		keep[path] = true
		if err := writeIfChanged(path, src); err != nil {
			return 0, err
		}
	}
	litPath := filepath.Join(internal, "jsonx", "lit", "lit_types.go")
	keep[litPath] = true
	if err := writeIfChanged(litPath, g.litFile(lits)); err != nil {
		return 0, err
	}
	for _, layer := range []string{"domain", "contracts", "application", "host"} {
		stale, _ := filepath.Glob(filepath.Join(internal, layer, "*_types.go"))
		for _, path := range stale {
			if keep[path] {
				continue
			}
			if data, err := os.ReadFile(path); err == nil && bytes.HasPrefix(data, []byte(header)) {
				if err := os.Remove(path); err != nil {
					return 0, err
				}
			}
		}
	}
	return len(keep), nil
}

func (g *gen) litFile(lits map[string]string) []byte {
	var out bytes.Buffer
	fmt.Fprintf(&out, "%s. DO NOT EDIT.\n\n// Package lit names every JSON constant a generated type carries as a jsonx.Tag.\npackage lit\n\n", header)
	texts := make([]string, 0, len(lits))
	for text := range lits {
		texts = append(texts, text)
	}
	slices.SortFunc(texts, func(a, b string) int { return strings.Compare(lits[a], lits[b]) })
	for _, text := range texts {
		name := lits[text]
		fmt.Fprintf(&out, "// %s is %s.\ntype %s struct{}\n\nfunc (%s) JSONLiteral() string { return %q }\n\n", name, text, name, name, text)
	}
	src, err := format.Source(out.Bytes())
	if err != nil {
		fail(err)
	}
	return src
}

func writeIfChanged(path string, data []byte) error {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o644)
}
